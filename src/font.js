// Pre-rendered offscreen tint cache for fast zero-GC text blitting
const glyphAtlasCache = new Map();

function getColorAtlas(color) {
  let entry = glyphAtlasCache.get(color);
  if (entry) return entry;
  if (typeof document === 'undefined') return null;

  const chars = Object.keys(GLYPH_MAP);
  const cellW = 6;
  const cellH = 8;
  const canvas = document.createElement('canvas');
  canvas.width = chars.length * cellW;
  canvas.height = cellH;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = color;

  const indexMap = new Map();
  chars.forEach((ch, idx) => {
    indexMap.set(ch, idx * cellW);
    const rows = GLYPH_MAP[ch];
    const ox = idx * cellW;
    for (let r = 0; r < 7; r++) {
      const bits = rows[r];
      for (let c = 0; c < 5; c++) {
        if ((bits >> (4 - c)) & 1) {
          ctx.fillRect(ox + c, r, 1, 1);
        }
      }
    }
  });

  entry = { canvas, indexMap, cellW, cellH };
  glyphAtlasCache.set(color, entry);
  return entry;
}

export function normalizeGlyphText(text) {
  return String(text ?? '')
    .replace(/\u2014/g, '--')
    .replace(/[\u2013\u2212]/g, '-')
    .replace(/[\u2018\u2019\u2032]/g, "'")
    .replace(/[\u201C\u201D\u2033]/g, '"')
    .replace(/\u2026/g, '...')
    .replace(/\u00A0/g, ' ')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

export function measurePixelText(text, scale = 1) {
  const str = normalizeGlyphText(text);
  if (!str.length) return { width: 0, height: 7 * scale };
  return {
    width: (str.length * 6 - 1) * scale,
    height: 7 * scale,
  };
}

export function wrapPixelText(text, maxWidthPx, scale = 1) {
  const words = normalizeGlyphText(text).split(/\s+/);
  const lines = [];
  let current = '';
  const charAdvance = 6 * scale;
  const maxChars = Math.max(4, Math.floor((maxWidthPx + scale) / charAdvance));

  for (const word of words) {
    if (!word) continue;
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length <= maxChars) {
      current = candidate;
    } else {
      if (current) lines.push(current);
      if (word.length > maxChars) {
        let rem = word;
        while (rem.length > maxChars) {
          lines.push(rem.slice(0, maxChars - 1) + '-');
          rem = rem.slice(maxChars - 1);
        }
        current = rem;
      } else {
        current = word;
      }
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [''];
}

export function drawPixelText(ctx, text, x, y, {
  color = 'white',
  shadow = null,
  scale = 1,
  align = 'left',
} = {}) {
  const str = normalizeGlyphText(text);
  if (!str) return 0;
  const w = (str.length * 6 - 1) * scale;
  let startX = Math.round(x);
  const startY = Math.round(y);
  if (align === 'center') startX = Math.round(x - w / 2);
  else if (align === 'right') startX = Math.round(x - w);

  if (shadow) {
    renderGlyphRun(ctx, str, startX + scale, startY + scale, shadow, scale);
  }
  renderGlyphRun(ctx, str, startX, startY, color, scale);
  return w;
}

function renderGlyphRun(ctx, str, x, y, color, scale) {
  const atlas = getColorAtlas(color);
  if (!atlas) return;
  let cx = x;
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    const sx = atlas.indexMap.has(ch)
      ? atlas.indexMap.get(ch)
      : (atlas.indexMap.get(ch.toUpperCase()) ?? atlas.indexMap.get('?'));
    ctx.drawImage(atlas.canvas, sx, 0, 5, 7, cx, y, 5 * scale, 7 * scale);
    cx += 6 * scale;
  }
}

export function drawWrappedPixelText(ctx, text, x, y, maxWidthPx, {
  color = 'white',
  shadow = null,
  scale = 1,
  lineHeight = 9,
  maxLines = 99,
  align = 'left',
} = {}) {
  const lines = wrapPixelText(text, maxWidthPx, scale).slice(0, maxLines);
  for (let i = 0; i < lines.length; i++) {
    drawPixelText(ctx, lines[i], x, y + i * lineHeight * scale, {
      color,
      shadow,
      scale,
      align,
    });
  }
  return lines.length * lineHeight * scale;
}
